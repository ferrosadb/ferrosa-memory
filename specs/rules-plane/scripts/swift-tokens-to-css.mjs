#!/usr/bin/env node
// Derive the prototype's CSS token block from the app's generated Swift tokens.
//
// The ferrosa-design skill's single-source-of-truth rule forbids copying hex
// values into another repo: "a second copy of the palette is a palette that
// drifts". The sanctioned pattern is the one the app already uses — GENERATE
// from the source and mark the output generated. This does the same, one hop
// further along: the app's Generated/FerrosaTokens.generated.swift is itself
// generated from ferrosadb.com/design-system.html, so a prototype derived from
// it moves when the app moves.
//
// Fail loud: an unparseable line is an error, never a skipped token.
import { readFileSync, writeFileSync } from "node:fs";

const [, , src, out] = process.argv;
if (!src || !out) {
  console.error("usage: swift-tokens-to-css.mjs <FerrosaTokens.generated.swift> <out.css>");
  process.exit(2);
}

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
// The gate's checks call the page ground "bg"; the app calls it "background".
const RENAME = { background: "bg" };

const argb = (hex) => {
  const n = parseInt(hex, 16);
  const a = (n >>> 24) & 0xff;
  const r = (n >>> 16) & 0xff;
  const g = (n >>> 8) & 0xff;
  const b = n & 0xff;
  const pad = (v) => v.toString(16).padStart(2, "0");
  // Opaque values stay #rrggbb so the contrast gate can read them; a token with
  // real alpha keeps it, because a tint over a different ground per theme is
  // exactly the composite the skill warns cannot be a literal.
  return a === 0xff
    ? `#${pad(r)}${pad(g)}${pad(b)}`
    : `rgba(${r}, ${g}, ${b}, ${(a / 255).toFixed(3).replace(/0+$/, "").replace(/\.$/, "")})`;
};

const text = readFileSync(src, "utf8");
const LINE = /static let (\w+) = dynamic\(dark: 0x([0-9A-Fa-f]{8}), light: 0x([0-9A-Fa-f]{8})\)/g;

const dark = [];
const light = [];
let count = 0;
for (const m of text.matchAll(LINE)) {
  const name = RENAME[m[1]] ?? kebab(m[1]);
  dark.push(`  --${name}: ${argb(m[2])};`);
  light.push(`  --${name}: ${argb(m[3])};`);
  count += 1;
}

const declared = (text.match(/static let \w+ = dynamic\(/g) || []).length;
if (count !== declared) {
  console.error(`parsed ${count} of ${declared} token declarations — refusing to emit a partial palette`);
  process.exit(1);
}
if (!count) {
  console.error("no tokens found; refusing to emit an empty palette");
  process.exit(1);
}

const css = `/* Generated by scripts/swift-tokens-to-css.mjs from the app's
   Generated/FerrosaTokens.generated.swift, which is itself generated from
   https://www.ferrosadb.com/design-system.html. Do not edit.

   Dark is Ferrosa's default, so it sits on bare :root. Light is declared twice:
   once for an explicit choice and once for the host setting. All three blocks
   are required by check-contrast.mjs — a missing one is an error, not a skip. */

:root {
${dark.join("\n")}
}

:root[data-theme="light"] {
${light.join("\n")}
}

@media (prefers-color-scheme: light) {
  :root:not([data-theme="dark"]) {
${light.map((l) => "  " + l).join("\n")}
  }
}
`;

writeFileSync(out, css);
console.log(`wrote ${out}: ${count} tokens x 3 theme blocks`);
